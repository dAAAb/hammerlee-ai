import fs from 'node:fs';

const data = JSON.parse(fs.readFileSync('public/assets/glyphs.json', 'utf8'));
const sources = ['src/conversation.js', 'src/branding.js', 'supabase/functions/journeys/og-image.js'];
const characters = new Set([...sources.map(path => fs.readFileSync(path, 'utf8')).join(''), ...'0123456789ABCDEFV /…']);
const glyphs = {};
function path(commands) {
  return commands.map(c => c.type === 'M' || c.type === 'L' ? `${c.type}${c.x} ${c.y}`
    : c.type === 'C' ? `C${c.x1} ${c.y1} ${c.x2} ${c.y2} ${c.x} ${c.y}`
      : c.type === 'Q' ? `Q${c.x1} ${c.y1} ${c.x} ${c.y}` : c.type === 'Z' ? 'Z' : '').join('');
}
for (const char of characters) {
  const glyph = data.glyphs[char];
  if (glyph) glyphs[char] = { advance: glyph.advance, path: path(glyph.commands) };
}
const output = `// Generated by scripts/build-og-glyphs.mjs. Noto Sans CJK TC Medium, SIL OFL 1.1.\n// Font license: public/assets/OFL.txt (retain with source redistribution).\nexport const glyphs = ${JSON.stringify(glyphs)};\n`;
fs.writeFileSync('supabase/functions/journeys/og-glyphs.js', output);
console.log(JSON.stringify({ glyphCount: Object.keys(glyphs).length, bytes: Buffer.byteLength(output) }));
